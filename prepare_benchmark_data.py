"""Prepare fixed benchmark inputs for the chapter experiment.

The raw EV records are the City of Boulder 2023 CC0 charging-session data.
Delivered energy is prorated uniformly over the recorded charging duration and
aggregated to hourly station demand. No stations or base demand values are
generated by this script.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parent
DATA_DIR = ROOT / "benchmark_data"
RAW_PATH = DATA_DIR / "boulder_ev_2023_sessions.csv"


def safe_duration(value: object) -> pd.Timedelta:
    try:
        duration = pd.to_timedelta(str(value))
    except (TypeError, ValueError):
        return pd.NaT
    if pd.isna(duration) or duration <= pd.Timedelta(0) or duration > pd.Timedelta(days=2):
        return pd.NaT
    return duration


def main() -> None:
    sessions = pd.read_csv(RAW_PATH)
    sessions["start"] = pd.to_datetime(sessions["Start_Date___Time"], format="%m/%d/%Y %H:%M", errors="coerce")
    sessions["energy_kwh"] = pd.to_numeric(sessions["Energy__kWh_"], errors="coerce")
    sessions["duration"] = sessions["Charging_Time__hh_mm_ss_"].map(safe_duration)
    sessions = sessions.dropna(subset=["Station_Name", "Address", "start", "energy_kwh", "duration"])
    sessions = sessions[
        (sessions["start"] >= "2023-01-01")
        & (sessions["start"] < "2024-01-01")
        & (sessions["energy_kwh"] >= 0)
    ].copy()

    station_names = sorted(sessions["Station_Name"].unique())
    station_id = {name: f"EV{i:02d}" for i, name in enumerate(station_names, start=1)}
    addresses = sorted(sessions["Address"].unique())
    site_id = {address: f"SITE{i:02d}" for i, address in enumerate(addresses, start=1)}
    sessions["station_id"] = sessions["Station_Name"].map(station_id)
    sessions["site_id"] = sessions["Address"].map(site_id)

    allocations: list[tuple[pd.Timestamp, str, float]] = []
    for row in sessions.itertuples(index=False):
        start = row.start
        finish = start + row.duration
        duration_hours = row.duration / pd.Timedelta(hours=1)
        if duration_hours <= 0:
            continue
        cursor = start.floor("h")
        while cursor < finish:
            next_hour = cursor + pd.Timedelta(hours=1)
            overlap = max(
                0.0,
                (min(finish, next_hour) - max(start, cursor)) / pd.Timedelta(hours=1),
            )
            if overlap > 0:
                allocations.append((cursor, row.station_id, row.energy_kwh * overlap / duration_hours))
            cursor = next_hour

    hourly_long = pd.DataFrame(allocations, columns=["timestamp", "station_id", "energy_kwh"])
    hourly = hourly_long.pivot_table(
        index="timestamp", columns="station_id", values="energy_kwh", aggfunc="sum", fill_value=0.0
    )
    full_index = pd.date_range("2023-01-01", "2023-11-30 23:00:00", freq="h")
    hourly = hourly.reindex(index=full_index, columns=list(station_id.values()), fill_value=0.0)
    hourly.index.name = "timestamp"
    hourly.to_csv(DATA_DIR / "boulder_ev_hourly_2023.csv", float_format="%.6f")

    station_summary = (
        sessions.groupby(["station_id", "Station_Name", "Address", "site_id", "Port_Type"], dropna=False)
        .agg(session_count=("energy_kwh", "size"), total_energy_kwh=("energy_kwh", "sum"))
        .reset_index()
        .sort_values("station_id")
    )
    station_summary.to_csv(DATA_DIR / "boulder_ev_station_metadata.csv", index=False, float_format="%.6f")

    site_summary = (
        station_summary.groupby(["site_id", "Address"], as_index=False)
        .agg(
            station_count=("station_id", "size"),
            session_count=("session_count", "sum"),
            total_energy_kwh=("total_energy_kwh", "sum"),
        )
        .sort_values("site_id")
    )
    site_summary.to_csv(DATA_DIR / "boulder_ev_site_summary.csv", index=False, float_format="%.6f")

    profile = hourly.copy()
    profile["hour_of_week"] = profile.index.dayofweek * 24 + profile.index.hour
    mean_profile = profile.groupby("hour_of_week").mean().reindex(range(168), fill_value=0.0)
    std_profile = profile.groupby("hour_of_week").std().reindex(range(168), fill_value=0.0).fillna(0.0)
    rows = []
    for how in range(168):
        for sid in hourly.columns:
            rows.append((how, sid, mean_profile.at[how, sid], std_profile.at[how, sid]))
    pd.DataFrame(rows, columns=["hour_of_week", "station_id", "mean_kw", "std_kw"]).to_csv(
        DATA_DIR / "boulder_ev_hour_of_week_profile.csv", index=False, float_format="%.6f"
    )

    edges: dict[tuple[str, str], tuple[str, float]] = {}
    for _, group in station_summary.groupby("site_id"):
        ids = sorted(group["station_id"].tolist())
        for i, source in enumerate(ids):
            for target in ids[i + 1 :]:
                edges[(source, target)] = ("same_site", 1.0)

    corr = mean_profile.corr().replace([np.inf, -np.inf], np.nan).fillna(-1.0)
    station_to_site = station_summary.set_index("station_id")["site_id"].to_dict()
    for source in hourly.columns:
        candidates = [
            target
            for target in hourly.columns
            if target != source and station_to_site[target] != station_to_site[source]
        ]
        candidates.sort(key=lambda target: float(corr.at[source, target]), reverse=True)
        for target in candidates[:2]:
            key = tuple(sorted((source, target)))
            if key not in edges:
                edges[key] = ("demand_similarity", max(0.0, float(corr.at[source, target])))

    edge_rows = [
        (source, target, relation, weight)
        for (source, target), (relation, weight) in sorted(edges.items())
    ]
    pd.DataFrame(edge_rows, columns=["source", "target", "relation", "weight"]).to_csv(
        DATA_DIR / "boulder_ev_edges.csv", index=False, float_format="%.6f"
    )

    manifest = f"""# Benchmark data manifest

- Power: MATPOWER `case33bw.m`, the 33-bus Baran-Wu distribution benchmark.
- Water: EPANET `Net3.inp`, including its two pumps and 24-hour demand patterns.
- EV charging: City of Boulder, Colorado, Electric Vehicle Charging Station Data.
  - Source: https://services.arcgis.com/ePKBjXrBZ2vEEgWd/arcgis/rest/services/Electric_Vehicle_Charging_Station_Data/FeatureServer/0
  - Fixed query: `Start_Date___Time LIKE '%2023%'`
  - Coverage in the downloaded file: 1 January to 30 November 2023.
  - License: CC0, as stated in the City of Boulder metadata.
  - Valid sessions used: {len(sessions):,}.
  - Observed charging ports: {len(station_names)} at {len(addresses)} addresses.
  - Processing: each session's delivered energy was prorated uniformly across its recorded charging duration and summed into hourly station energy. Hourly energy in kWh is numerically equal to mean kW over that hour.

Randomness is used later only for train/test resampling, measurement noise, sensor dropout, and cyberattack placement. It is not used to create the benchmark systems, charging stations, or base EV demand.
"""
    (DATA_DIR / "README.md").write_text(manifest, encoding="utf-8")

    print(f"Prepared {len(sessions):,} sessions, {len(station_names)} stations, and {len(addresses)} sites.")
    print(f"Hourly matrix: {hourly.shape[0]} hours x {hourly.shape[1]} stations")


if __name__ == "__main__":
    main()
